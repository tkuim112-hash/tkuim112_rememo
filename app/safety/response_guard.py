# 這條檢查最早是用regex（「我／我們」接固定收錄的關鍵詞：記得/想起/想念/
# 那時候/以前/小時候/當年/家/媽媽/爸爸），後來實測發現至少兩個問題：
#   1. false positive——長者自己說「我們家比較吃比較清淡」，AI用「你說」
