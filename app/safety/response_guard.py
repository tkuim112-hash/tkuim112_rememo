# （「這句話有沒有把AI自己講成有親身經歷」），改用LLM語意分類取代——跟
# taboo_checker.py 的 llm_topic_check 是同一種設計：把判斷交給LLM本身
# 做，不要求窮舉所有可能的字面組合，temperature=0求判斷盡量穩定、失敗
# 就保守視為違規（fail-safe），理由都跟 llm_topic_check 一致。
