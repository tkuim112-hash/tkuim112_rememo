# 2026-09-13稽核（使用者提案，同一天稽核，實測後拿回）：批次品質測試
# （manual_test_real_transcripts.py）用真實長者原話重跑，證實完全不做
# 事後偵測後，這個失效模式確實會漏到最終送給長者聽的輸出（例如長者只說
